def generate_username():
    """Генерирует случайный юзернейм длиной 3-8 символов."""

    # --------------------------------------------------------
    # TODO 1: собери список длин
    # --------------------------------------------------------
    # ПОДСКАЗКА: lengths = [8]*30 + [7]*25 + ... + [3]*5
    # Распиши шесть длин: 8, 7, 6, 5, 4, 3
    # с количеством повторений: 30, 25, 20, 15, 10, 5

    lengths = [8]*30 + [7]*25 + [6]*20 + [5]*15 + [4]*10 + [3]*5

    # --------------------------------------------------------
    # TODO 2: выбери случайную длину
    # --------------------------------------------------------
    # ПОДСКАЗКА: random.choice(список)

    n = random.choice(lengths)

    # --------------------------------------------------------
    # TODO 3: выбери набор символов
    # --------------------------------------------------------
    # 90% буквы, 10% цифры.
    # ПОДСКАЗКА: random.random() < 0.9
    # ПОДСКАЗКА: string.ascii_lowercase / string.digits

    if random.random() < 0.9:
        pool = string.ascii_lowercase
    else:
        pool = string.digits

    # --------------------------------------------------------
    # TODO 4: собери строку из n случайных символов
    # --------------------------------------------------------
    # ПОДСКАЗКА: "".join(random.choice(pool) for _ in range(n))

    tag = "".join(random.choice(pool) for _ in range(n))
    return tag


def generate_by_pattern():
    """Генерирует ник по шаблону: префикс + число + суффикс."""

    # --------------------------------------------------------
    # TODO 5: список префиксов
    # --------------------------------------------------------
    prefixes = ["dark", "neo", "king", "tops", "lol"]

    # --------------------------------------------------------
    # TODO 6: список суффиксов
    # --------------------------------------------------------
    suffixes = ["pro", "x", "gg", "tv", "hd", "max", "op"]

    # --------------------------------------------------------
    # TODO 7: выбери случайные части
    # --------------------------------------------------------
    p = random.choice(prefixes)
    s = random.choice(suffixes)
    num = random.randint(1, 99)

    # --------------------------------------------------------
    # TODO 8: склей всё в одну строку
    # --------------------------------------------------------
    tag = p + str(num) + s
    return tag


def generate_leet():
    """Генерирует ник с заменой букв на цифры (leet-стиль)."""

    # --------------------------------------------------------
    # TODO 9: словарь замен
    # --------------------------------------------------------
    leet = {"a": "4", "e": "3", "i": "1", "o": "0", "s": "5", "t": "7"}

    # --------------------------------------------------------
    # TODO 10: список слов
    # --------------------------------------------------------
    words = ["hacker", "ghost", "cyber", "ninja", "wolf",
             "fox", "dark", "neon", "void", "king"]
    word = random.choice(words)

    # --------------------------------------------------------
    # TODO 11: замени буквы на цифры
    # --------------------------------------------------------
    result = ""
    for ch in word:
        result += leet.get(ch, ch)

    return result



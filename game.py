def calculate_multiplier(tag):
    """Возвращает (mult, bonuses) — число и список бонусов."""
    mult = 1
    n = len(tag)
    bonuses = []

    # --- Правило 1: длина ---
    if n == 8:
        mult *= 2
        bonuses.append(("Длина 8 (x2)", 2))
    elif n == 7:
        mult *= 4
        bonuses.append(("Длина 7 (x4)", 4))
    elif n == 6:
        mult *= 10
        bonuses.append(("Длина 6 (x10)", 10))
    elif n == 5:
        mult *= 30
        bonuses.append(("Длина 5 (x30)", 30))
    elif n == 4:
        mult *= 60
        bonuses.append(("Длина 4 (x60)", 60))
    elif n == 3:
        mult *= 100
        bonuses.append(("Длина 3 (x100)", 100))
    else:
        return 0, []

    # --- Правило 2: палиндром ---
    if tag == tag[::-1]:
        mult *= 8
        bonuses.append(("Палиндром (x8)", 8))

    # --- Правило 3: все символы одинаковые ---
    if len(set(tag)) == 1:
        mult *= 100
        bonuses.append(("Все символы одинаковые (x100)", 100))

    # --- Правило 4: только буквы ---
    if tag.isalpha():
        mult *= 2
        bonuses.append(("Только буквы (x2)", 2))

    # --- Правило 5: максимальная серия ---
    max_len = 1
    cur_len = 1
    for i in range(1, n):
        if tag[i] == tag[i-1]:
            cur_len += 1
        else:
            cur_len = 1
        if cur_len > max_len:
            max_len = cur_len

    if max_len == 3:
        mult *= 3
        bonuses.append(("Серия из 3 одинаковых (x3)", 3))
    elif max_len == 4:
        mult *= 10
        bonuses.append(("Серия из 4 одинаковых (x10)", 10))
    elif max_len >= 5:
        mult *= 50
        bonuses.append((f"Серия из {max_len} одинаковых (x50)", 50))

    # --------------------------------------------------------
    # TODO 1 (часть 3): три одинаковые цифры подряд → x8
    # --------------------------------------------------------
    # ПОДСКАЗКА: for i in range(n - 2)
    # ПОДСКАЗКА: a, b, c = tag[i], tag[i+1], tag[i+2]
    # ПОДСКАЗКА: if a == b == c and a.isdigit():
    # ПОДСКАЗКА: mult *= 8, bonuses.append(...), break

    for i in range(n - 2):
        a, b, c = tag[i], tag[i+1], tag[i+2]
        if a == b == c and a.isdigit():
            mult *= 8
            bonuses.append((f"Три цифры {a}{a}{a} (x8)", 8))
            break

    # --------------------------------------------------------
    # TODO 2 (часть 3): спецкомбинации 111 / 666 / 777 → x15
    # --------------------------------------------------------
    # ПОДСКАЗКА: special = ["111", "666", "777"]
    # ПОДСКАЗКА: if tag[i:i+3] in special:
    # ПОДСКАЗКА: mult *= 15, bonuses.append(...), break

    special = ["111", "666", "777"]
    for i in range(n - 2):
        if tag[i:i+3] in special:
            mult *= 15
            bonuses.append((f"Спецкомбинация {tag[i:i+3]} (x15)", 15))
            break

    # --------------------------------------------------------
    # TODO 3 (часть 3): повтор блока ababab → x12
    # --------------------------------------------------------
    # ПОДСКАЗКА: for i in range(n - 5)
    # ПОДСКАЗКА: tag[i] == tag[i+2] == tag[i+4]
    #            и одновременно
    #            tag[i+1] == tag[i+3] == tag[i+5]
    # ПОДСКАЗКА: mult *= 12, bonuses.append(...), break

    for i in range(n - 5):
        if (tag[i] == tag[i+2] == tag[i+4] and
                tag[i+1] == tag[i+3] == tag[i+5]):
            mult *= 12
            bonuses.append((f"Повтор блока {tag[i:i+6]} (x12)", 12))
            break

    return mult, bonuses


def get_rarity(mult):
    """Редкость и эмодзи по множителю."""
    if mult >= 20000: return "Мифический", "🔴"
    if mult >= 5000:  return "Легендарный", "🟠"
    if mult >= 1000:  return "Эпический", "🟣"
    if mult >= 300:   return "Редкий", "🔵"
    if mult >= 100:   return "Необычный", "🟢"
    return "Обычный", "⚪"


def spin_username():
    generators = [generate_username, generate_by_pattern, generate_leet]
    generator = random.choice(generators)

    tag = generator()

    multiplier, bonuses = calculate_multiplier(tag)

    rarity, emoji = get_rarity(multiplier)

    price = max(
        5,
        int(multiplier * 2 * random.uniform(0.8, 1.2))
    )

    return {
        "username": tag,
        "multiplier": multiplier,
        "rarity": rarity,
        "emoji": emoji,
        "price": price,
        "bonuses": bonuses
    }

    
